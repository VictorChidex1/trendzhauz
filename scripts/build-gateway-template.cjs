/**
 * Predeploy helper — copies the Vite-built SPA shell (dist/index.html)
 * into the Functions source tree so seoGateway can serve the exact
 * built HTML with correct asset hashes to human visitors.
 *
 * Runs during `firebase deploy` via both hosting.predeploy and
 * functions.predeploy (double build, but guarantees functions-only
 * deploys never ship a stale or missing template).
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const DIST_HTML = path.join(ROOT, "dist", "index.html");
const OUT_DIR = path.join(ROOT, "functions", "src", "templates");
const OUT_FILE = path.join(OUT_DIR, "spa-shell.ts");

if (!fs.existsSync(DIST_HTML)) {
  console.error("❌ dist/index.html not found. Run `npm run build` first.");
  process.exit(1);
}

const raw = fs.readFileSync(DIST_HTML, "utf-8");

// Escape template literal backticks, backslashes, and dollar-brace
// so the HTML content can be safely embedded in a TypeScript string.
const escaped = raw
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

const ts = [
  "// AUTO-GENERATED by scripts/build-gateway-template.cjs — DO NOT EDIT",
  "// This file is regenerated on every firebase deploy.",
  `export const SPA_SHELL = \`${escaped}\`;`,
  "",
].join("\n");

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT_FILE, ts, "utf-8");

console.log("✅ Generated functions/src/templates/spa-shell.ts");
